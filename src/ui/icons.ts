export type IconName = keyof typeof Icons;

export function icon(name: IconName, size = 16, color = 0xffffff): Text {
    const t = new Text({
        text: Icons[name],
        style: textStyle({
            font: Fonts.iconSolid,
            weight: '900',
            size,
            color,
            align: 'center',
        }),
    });
    t.anchor.set(0.5);
    t.eventMode = 'none';
    return t;
}
